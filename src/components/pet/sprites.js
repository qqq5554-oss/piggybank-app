// 小寵物的像素圖。每張圖是一組字串，「#」是亮起來的點，其他是空白。
// 單色液晶螢幕的風格（經典電子雞），所以只需要一種顏色。

const parse = (rows) => {
  const pts = [];
  rows.forEach((row, y) => [...row].forEach((ch, x) => ch === "#" && pts.push([x, y])));
  return { w: rows[0].length, h: rows.length, pts };
};

