// 刺蝟、兔子的新版像素圖（參考使用者提供的電子雞風格）：
// 22×21 的圓滾滾身體、豆豆眼、小小的嘴、兩側小手、短短的腳。
// 兩種動物畫在同一個框裡（臉、手的位置一樣），所以表情和道具可以共用。
// 「#」是亮點；道具裡的「o」代表「擦掉後面的東西」（例如浴缸會蓋住腳）。

const parse = (rows) => {
  const pts = [];
  const clear = [];
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === "#") pts.push([x, y]);
      else if (ch === "o") clear.push([x, y]);
    })
  );
  return { w: rows[0].length, h: rows.length, pts, clear };
};

